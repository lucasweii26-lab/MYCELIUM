function detect() {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved && SUPPORTED.includes(saved)) return saved;
  } catch (error) { /* storage unavailable */ }
  const browser = (navigator.language || "en").toLowerCase();
  if (browser.startsWith("zh")) return "zh-CN";
  const base = browser.split("-")[0];
  return SUPPORTED.includes(base) ? base : "en";
}

let current = detect();

export const lang = () => current;
export function setLang(code) {
  if (!SUPPORTED.includes(code)) return;
  current = code;
  try { localStorage.setItem(STORAGE_KEY, code); } catch (error) { /* storage unavailable */ }
}

export const dateLocale = () => current;

// tr("Welcome, {name}", { name }) -> translated text with the {placeholders} filled in.
export function tr(text, vars) {
  const raw = text == null ? "" : String(text);
  let out = (current !== "en" && TABLES[current] && TABLES[current][raw]) || raw;
  if (vars) out = out.replace(/\{(\w+)\}/g, (match, key) => (key in vars ? vars[key] : match));
  return out;
}
